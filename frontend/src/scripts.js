export function getSprite(pet) {
  if (!pet) return EGG;
  if (pet.life_stage === "egg") return EGG;
  if (pet.life_stage === "graduated") {
    return SPRITES[pet.character_type]?.[pet.evolution_form] ?? SPRITES[0].normal;
  }
  // During growth, show base form; at adult show evolution form
  if (pet.life_stage === "adult") {
    return SPRITES[pet.character_type]?.[pet.evolution_form] ?? SPRITES[pet.character_type]?.normal ?? EGG;
  }
  return SPRITES[pet.character_type]?.normal ?? EGG;
}
 
